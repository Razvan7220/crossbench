"""Always-on LiteLLM step counter for SEAL Pro runs.

Registers a minimal ``CustomLogger`` that counts every
``litellm.completion`` call inside the SEAL subprocess and logs one
stderr line per call. Independent of which memory hook (if any) is
active — baseline (``no_memory``) cells get step counts too, fixing the gap
where ``_extract_traj_summary`` always reported ``steps_taken=1``
for the existing scaffold.

Output shape (one line per LLM call, visible in CloudWatch):

    [step-counter] llm_call step=0
    [step-counter] llm_call step=1
    [step-counter] llm_call step=2
    ...

End-of-task summary is emitted from ``seal.py`` via the structured
logger (``seal.step_count``) so per-task totals are searchable in
CloudWatch without scanning the per-call stream.

Composability with a memory hook: both can be registered together on
``litellm.callbacks``. The step counter only counts; a memory hook
handles recall/store. No interference between them.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

#: Env var the step counter writes its count to (read by seal.py
#: end-of-task summary). When the counter is registered, this file
#: holds the final step count after the SEAL subprocess exits.
#: Defaults to the same per-task tempdir seal.py uses for per-task
#: metrics files.
ENV_STEP_COUNT_FILE = "CROSSBENCH_STEP_COUNT_FILE"


#: Module-level call counter. List-wrapped so test helpers can reset
#: it without touching the module binding.
_step_counter: list[int] = [0]


def _reset_counter() -> None:
    """Reset the counter (used by tests; not called in production)."""
    _step_counter[0] = 0


def _write_count() -> None:
    """Persist the current count to the env-configured file (best effort)."""
    path = os.environ.get(ENV_STEP_COUNT_FILE, "").strip()
    if not path:
        return
    try:
        Path(path).write_text(str(_step_counter[0]))
    except OSError:
        pass


def register_step_counter() -> None:
    """Attach a minimal step-counting ``CustomLogger`` to litellm.callbacks.

    Idempotent: subsequent calls are no-ops if a ``StepCounter`` is
    already in the callbacks list.
    """
    try:
        import litellm
        from litellm.integrations.custom_logger import CustomLogger
    except ImportError:
        return

    # Avoid double-registration if the sitecustomize stub fires twice
    # (e.g., due to a Python reload).
    for cb in getattr(litellm, "callbacks", []):
        if cb.__class__.__name__ == "StepCounter":
            return

    class StepCounter(CustomLogger):  # type: ignore[misc]
        def log_pre_api_call(  # type: ignore[override]
            self, model: str, messages: list, kwargs: dict
        ) -> None:
            step = _step_counter[0]
            _step_counter[0] = step + 1
            print(
                f"[step-counter] llm_call step={step}",
                file=sys.stderr,
                flush=True,
            )
            # Persist after every step so a crashed subprocess still
            # leaves the count behind for the parent to harvest.
            _write_count()

    litellm.callbacks.append(StepCounter())


#: Sitecustomize stub written into every SEAL subprocess's PYTHONPATH.
#: Python's site-init imports ``sitecustomize`` automatically at
#: interpreter startup, so the counter registers BEFORE the first
#: ``litellm.completion`` fires inside sweagent.
SITECUSTOMIZE_STUB = """\
# Auto-generated by CrossBench SEAL scaffold. Registers an always-on
# step counter that logs every litellm.completion call to stderr.
# Independent of the memory hook — fires for baseline (no_memory)
# cells too. A memory hook (when active) registers separately on top.
try:
    from cross_bench.execution.scaffolds.step_counter_hook import (
        register_step_counter,
    )
    register_step_counter()
except Exception:
    pass

# Optional LLM I/O trace hook — only registers when
# CROSSBENCH_LLM_TRACE_ENABLED=1. Dumps every litellm.completion
# request and response to stderr (prefixed [llm-trace]). Loaded
# here so baseline (no-memory) cells can also use the trace; the
# hook's idempotency guard (callbacks list dedup) makes a second
# registration a no-op.
try:
    from cross_bench.execution.scaffolds.llm_trace_hook import (
        register_llm_trace_hook,
    )
    register_llm_trace_hook()
except Exception:
    pass
"""


def write_sitecustomize_stub(target_dir: str) -> str:
    """Write the step-counter ``sitecustomize.py`` + a copy of this module to ``target_dir``.

    Returns the absolute path to the written ``sitecustomize.py``. Copies
    this module next to the stub so the local ``import step_counter_hook``
    works even when the ``cross_bench`` package isn't importable from the
    sweagent subprocess. Caller is responsible
    for prepending ``target_dir`` to the subprocess's ``PYTHONPATH``.
    """
    import shutil

    target = Path(target_dir)
    target.mkdir(parents=True, exist_ok=True)
    stub_path = target / "sitecustomize.py"
    stub_path.write_text(SITECUSTOMIZE_STUB)
    # Copy THIS module's source next to the stub so the local import
    # works without a parent-package dependency.
    src_path = Path(__file__).resolve()
    dst_path = target / "step_counter_hook.py"
    try:
        shutil.copyfile(str(src_path), str(dst_path))
    except OSError:
        pass
    # Also copy llm_trace_hook.py so the stub's optional registration
    # works on baseline (no-memory) cells too.
    try:
        trace_src = src_path.parent / "llm_trace_hook.py"
        if trace_src.exists():
            shutil.copyfile(str(trace_src), str(target / "llm_trace_hook.py"))
    except OSError:
        pass
    return str(stub_path)
