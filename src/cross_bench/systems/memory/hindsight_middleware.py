"""Hindsight memory middleware — HTTP API client for the Hindsight memory platform.

Hindsight is an open-source agent memory platform by Vectorize.io that provides
persistent, structured memory for AI agents.  It goes beyond conversation log
replay: it extracts atomic facts, builds entity/temporal/semantic/causal graphs,
consolidates observations over time, and enables reflective reasoning.

Three core operations mirror human cognition:
  - **Retain** — ingest text, extract atomic facts, build entity + temporal +
    semantic + causal links.  Backed by PostgreSQL + pgvector.
  - **Recall** — 4-way parallel retrieval (semantic vector search, BM25 keyword,
    graph traversal, temporal spreading) with cross-encoder reranking.
  - **Reflect** — agentic multi-step reasoning that searches mental models,
    observations, and raw facts, then synthesises an answer.

Memory is organised into three fact types:
  - **world** — facts about the environment
  - **experience** — the agent's own events
  - **observation** — consolidated knowledge generated by the system

Install & run:
    docker run -d --name hindsight -p 8888:8888 \\
        -e HINDSIGHT_API_LLM_PROVIDER=openai \\
        -e HINDSIGHT_API_LLM_API_KEY=sk-… \\
        vectorize/hindsight

    # or via pip for embedded mode:
    pip install hindsight-all
    python -c "from hindsight import HindsightEmbedded; ..."

API reference (FastAPI on port 8888):
    POST /v1/default/banks/{bank_id}/retain  — store memories
    POST /v1/default/banks/{bank_id}/recall  — query memories
    POST /v1/default/banks/{bank_id}/reflect — agentic reflection
    POST /v1/default/banks                   — create a memory bank
    GET  /health                             — health check

Source:
    https://github.com/vectorize-io/hindsight

NOTE: When the Hindsight server is unavailable, the middleware falls back to
a simple in-memory keyword store so benchmarks can still run.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Any

from cross_bench.models import MemoryConfig
from cross_bench.systems.base import MemoryMiddleware
from cross_bench.systems.registry import register_memory

logger = logging.getLogger(__name__)


@register_memory("hindsight_api")
class HindsightMiddleware(MemoryMiddleware):
    """Hindsight REST API memory middleware.

    Config params (all go in ``MemoryConfig.params``):
        base_url:       Hindsight API URL (default ``http://localhost:8888``)
        bank_id:        Memory bank ID to use (default ``bench``)
        bank_name:      Human-readable bank name (default ``Bench Platform``)
        use_reflect:    If True, use the agentic ``/reflect`` endpoint for
                        retrieval instead of ``/recall`` (default False)
        recall_budget:  Token budget for recall results (default 2000)
        recall_types:   Fact types to recall: ``world``, ``experience``,
                        ``observation`` (default: all)
        retain_async:   If True, retain calls are async (default False)
        top_k:          Max results from recall (default 10)
        timeout:        HTTP timeout in seconds (default 30)
        max_retries:    Max retries on failure (default 3)
        api_key:        Optional API key for authenticated deployments
        create_bank:    Auto-create the bank if it doesn't exist (default True)
        mission:        Bank mission statement (guides fact extraction)
        disposition:    Dict of disposition traits (skepticism, literalism,
                        empathy) with values 1-5
    """

    def __init__(self, config: MemoryConfig):
        self._config = config
        p = config.params or {}
        self._base_url = p.get("base_url", "http://localhost:8888").rstrip("/")
        self._bank_id = p.get("bank_id", "bench")
        self._bank_name = p.get("bank_name", "Bench Platform")
        self._use_reflect = p.get("use_reflect", False)
        self._recall_budget = p.get("recall_budget", 2000)
        self._recall_types = p.get("recall_types", None)  # None = all types
        self._retain_async = p.get("retain_async", False)
        self._top_k = p.get("top_k", 10)
        self._timeout = p.get("timeout", 30)
        self._max_retries = p.get("max_retries", 3)
        self._api_key = p.get("api_key", "")
        self._create_bank = p.get("create_bank", True)
        self._mission = p.get("mission", "")
        self._disposition = p.get("disposition", {})

        # State
        self._fallback_memories: list[dict[str, Any]] = []
        self._server_available: bool | None = None
        self._bank_created: bool = False

    def _headers(self) -> dict[str, str]:
        """Build HTTP headers including optional auth."""
        h: dict[str, str] = {"Content-Type": "application/json"}
        if self._api_key:
            h["Authorization"] = f"Bearer {self._api_key}"
        return h

    @property
    def _bank_url(self) -> str:
        return f"{self._base_url}/v1/default/banks/{self._bank_id}"

    # ------------------------------------------------------------------
    # Server health + bank creation
    # ------------------------------------------------------------------

    async def _check_server(self) -> bool:
        """Check if Hindsight server is reachable, create bank if needed."""
        if self._server_available is not None:
            return self._server_available

        import httpx

        try:
            async with httpx.AsyncClient(timeout=5) as client:
                resp = await client.get(
                    f"{self._base_url}/health", headers=self._headers()
                )
                self._server_available = resp.status_code == 200
        except Exception:
            self._server_available = False
            logger.warning(
                "Hindsight server not available at %s — using in-memory fallback",
                self._base_url,
            )

        if self._server_available and self._create_bank and not self._bank_created:
            await self._ensure_bank()

        return self._server_available

    async def _ensure_bank(self) -> None:
        """Create the memory bank if it doesn't already exist."""
        import httpx

        try:
            async with httpx.AsyncClient(timeout=self._timeout) as client:
                # Check if bank exists
                resp = await client.get(
                    f"{self._bank_url}/profile", headers=self._headers()
                )
                if resp.status_code == 200:
                    self._bank_created = True
                    return

                # Create the bank
                body: dict[str, Any] = {
                    "bank_id": self._bank_id,
                    "name": self._bank_name,
                }
                if self._mission:
                    body["mission"] = self._mission
                if self._disposition:
                    body["disposition"] = self._disposition

                resp = await client.post(
                    f"{self._base_url}/v1/default/banks",
                    json=body,
                    headers=self._headers(),
                )
                if resp.status_code in (200, 201, 409):  # 409 = already exists
                    self._bank_created = True
                    logger.info("Hindsight bank '%s' ready", self._bank_id)
                else:
                    logger.warning(
                        "Failed to create Hindsight bank: %s %s",
                        resp.status_code,
                        resp.text[:200],
                    )
        except Exception as e:
            logger.warning("Failed to ensure Hindsight bank: %s", e)

    async def is_indexed(self) -> bool:
        """Check if memory indexing is complete (for indexing wait phase).

        Hindsight processes retain calls synchronously by default, but async
        retain may have pending operations.  Check via the operations endpoint.
        """
        if not self._retain_async:
            return True  # sync retain = always indexed

        import httpx

        try:
            async with httpx.AsyncClient(timeout=self._timeout) as client:
                resp = await client.get(
                    f"{self._bank_url}/operations",
                    params={"status": "pending", "limit": 1},
                    headers=self._headers(),
                )
                if resp.status_code == 200:
                    ops = resp.json()
                    pending = ops if isinstance(ops, list) else ops.get("operations", [])
                    return len(pending) == 0
        except Exception:
            pass
        return True

    # ------------------------------------------------------------------
    # MemoryMiddleware interface
    # ------------------------------------------------------------------

    async def pre_prompt(self, prompt: str, context: dict[str, Any]) -> str:
        """Search Hindsight for relevant memories and prepend to prompt.

        Uses /recall (default) or /reflect (if use_reflect=True).
        """
        # Boundary (CrossBench↔middleware seam): tokenize the query.
        self._record_io(request_text=prompt[:2000])

        if not await self._check_server():
            return self._fallback_search(prompt)

        import httpx

        query = prompt[:2000]

        if self._use_reflect:
            return await self._reflect_search(query, prompt)

        # Recall: structured retrieval
        body: dict[str, Any] = {
            "query": query,
            "max_tokens": self._recall_budget,
        }
        if self._recall_types:
            body["types"] = (
                self._recall_types
                if isinstance(self._recall_types, list)
                else [t.strip() for t in self._recall_types.split(",")]
            )

        for attempt in range(self._max_retries):
            try:
                async with httpx.AsyncClient(timeout=self._timeout) as client:
                    resp = await client.post(
                        f"{self._bank_url}/recall",
                        json=body,
                        headers=self._headers(),
                    )
                    if resp.status_code == 200:
                        data = resp.json()
                        results = data.get("results", [])
                        if results:
                            formatted = self._format_recall_results(
                                results, prompt
                            )
                            if isinstance(formatted, str) and formatted.endswith(
                                prompt
                            ):
                                self._record_io(
                                    response_text=formatted[: -len(prompt)]
                                )
                            return formatted
                    return prompt
            except Exception as e:
                if attempt < self._max_retries - 1:
                    await asyncio.sleep(1.0 * (attempt + 1))
                else:
                    logger.warning("Hindsight recall failed after retries: %s", e)

        return prompt

    async def _reflect_search(self, query: str, prompt: str) -> str:
        """Use Hindsight's agentic /reflect endpoint for retrieval."""
        import httpx

        body: dict[str, Any] = {
            "query": query,
            "max_tokens": self._recall_budget,
        }

        for attempt in range(self._max_retries):
            try:
                async with httpx.AsyncClient(timeout=self._timeout * 3) as client:
                    resp = await client.post(
                        f"{self._bank_url}/reflect",
                        json=body,
                        headers=self._headers(),
                    )
                    if resp.status_code == 200:
                        data = resp.json()
                        text = data.get("text", "")
                        based_on = data.get("based_on", [])
                        if text:
                            # Format reflection + source facts
                            lines = [f"[Reflection] {text}"]
                            for fact in based_on[:5]:
                                if isinstance(fact, dict):
                                    lines.append(
                                        f"  - {fact.get('text', fact.get('content', str(fact)))}"
                                    )
                                elif isinstance(fact, str):
                                    lines.append(f"  - {fact}")
                            memory_text = "\n".join(lines)
                            return f"Retrieved memories:\n{memory_text}\n\n{prompt}"
                    return prompt
            except Exception as e:
                if attempt < self._max_retries - 1:
                    await asyncio.sleep(1.0 * (attempt + 1))
                else:
                    logger.warning("Hindsight reflect failed after retries: %s", e)

        return prompt

    async def post_response(
        self, prompt: str, response: str, context: dict[str, Any]
    ) -> None:
        """Store text in Hindsight via the /retain endpoint."""
        # Boundary: tokenize the content we ship to the Hindsight server.
        self._record_io(request_text=response[:4000])

        if not await self._check_server():
            self._fallback_memories.append({"text": response[:2000]})
            return

        import httpx

        # Build retain item following Hindsight API format
        item: dict[str, Any] = {
            "content": response[:4000],
        }

        # Add optional metadata
        if context.get("timestamp"):
            item["event_date"] = context["timestamp"]
        if context.get("conversation_id"):
            item["tags"] = [f"conv:{context['conversation_id']}"]
        if context.get("task_id"):
            item.setdefault("tags", []).append(f"task:{context['task_id']}")

        body: dict[str, Any] = {
            "items": [item],
            "async": self._retain_async,
        }

        for attempt in range(self._max_retries):
            try:
                async with httpx.AsyncClient(timeout=self._timeout) as client:
                    resp = await client.post(
                        f"{self._bank_url}/retain",
                        json=body,
                        headers=self._headers(),
                    )
                    if resp.status_code in (200, 201, 202):
                        return
                    else:
                        logger.debug(
                            "Hindsight retain returned %s: %s",
                            resp.status_code,
                            resp.text[:200],
                        )
            except Exception as e:
                if attempt < self._max_retries - 1:
                    await asyncio.sleep(1.0 * (attempt + 1))
                else:
                    logger.warning("Hindsight retain failed after retries: %s", e)
                    self._fallback_memories.append({"text": response[:2000]})

    async def reset(self) -> None:
        """Clear session state.

        Clears the fallback in-memory store.  Does NOT delete data from
        the Hindsight server — the persistent memory bank is the whole point.
        Server-side cleanup should be done externally if needed.
        """
        self._fallback_memories.clear()
        self._reset_internal_counters()

    # ------------------------------------------------------------------
    # Formatting helpers
    # ------------------------------------------------------------------

    def _format_recall_results(
        self, results: list[dict[str, Any]], prompt: str
    ) -> str:
        """Format Hindsight recall results as context for the prompt.

        Hindsight recall returns results with fields:
          - text: the fact text
          - fact_type: world | experience | observation
          - score: relevance score
          - event_date: when the fact occurred
          - entities: related entities
          - metadata: additional context
        """
        lines = []
        for r in results:
            text = r.get("text", r.get("content", str(r)))
            fact_type = r.get("fact_type", r.get("type", ""))
            score = r.get("score", "")
            event_date = r.get("event_date", "")

            prefix = f"[{fact_type}]" if fact_type else "-"
            suffix_parts = []
            if isinstance(score, (int, float)):
                suffix_parts.append(f"score={score:.3f}")
            if event_date:
                suffix_parts.append(f"date={event_date}")
            suffix = f" ({', '.join(suffix_parts)})" if suffix_parts else ""

            lines.append(f"{prefix} {text}{suffix}")

        memory_text = "\n".join(lines)
        return f"Retrieved memories:\n{memory_text}\n\n{prompt}"

    def _fallback_search(self, prompt: str) -> str:
        """Simple keyword search over in-memory fallback store."""
        if not self._fallback_memories:
            return prompt

        query_words = set(prompt.lower().split()[:15])
        scored = []
        for mem in self._fallback_memories:
            text = mem.get("text", "")
            overlap = sum(1 for w in query_words if w in text.lower())
            if overlap > 0:
                scored.append((overlap, text))

        scored.sort(key=lambda x: x[0], reverse=True)
        top = [t for _, t in scored[: self._top_k]]
        if top:
            memory_text = "\n".join(f"- {t}" for t in top)
            return f"Retrieved memories:\n{memory_text}\n\n{prompt}"
        return prompt
